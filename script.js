const modal = document.getElementById("detailsModal");
const modalOverlay = document.getElementById("modalOverlay");
const closeModal = document.getElementById("closeModal");

const detailsImage = document.getElementById("detailsImage");
const detailsImageText = document.getElementById("detailsImageText");
const detailsCategory = document.getElementById("detailsCategory");
const detailsTitle = document.getElementById("detailsTitle");
const detailsLocation = document.getElementById("detailsLocation");
const detailsAbout = document.getElementById("detailsAbout");
const detailsHistory = document.getElementById("detailsHistory");
const detailsWhy = document.getElementById("detailsWhy");
const detailsTips = document.getElementById("detailsTips");
const planPlace = document.getElementById("planPlace");

let selectedPlace = null;

function openPlace(placeId) {
    const place = places[placeId];

    if (!place) return;

    selectedPlace = place;

    detailsCategory.textContent = place.category;
    detailsTitle.textContent = place.title;
    detailsLocation.textContent = "📍 " + place.location;
    detailsAbout.textContent = place.about;
    detailsHistory.textContent = place.history;

    detailsWhy.innerHTML = "";
    place.why.forEach(item => {
        const li = document.createElement("li");
        li.textContent = item;
        detailsWhy.appendChild(li);
    });

    detailsTips.innerHTML = "";
    place.tips.forEach(item => {
        const li = document.createElement("li");
        li.textContent = item;
        detailsTips.appendChild(li);
    });

    detailsImage.style.setProperty("--detail-image", `url("${place.image}")`);
    detailsImage.style.backgroundImage = `url("${place.image}")`;
    detailsImageText.textContent = "Your place image";

    // If the user has not added the image yet, show a friendly placeholder.
    const testImage = new Image();
    testImage.onload = () => {
        detailsImage.style.backgroundImage = `url("${place.image}")`;
        detailsImageText.style.display = "none";
    };
    testImage.onerror = () => {
        detailsImage.style.backgroundImage =
            "linear-gradient(135deg, #dce9df, #bcd2c3)";
        detailsImageText.style.display = "inline-block";
        detailsImageText.textContent = "Add your image in the images folder";
    };
    testImage.src = place.image;

    modal.classList.add("open");
    document.body.style.overflow = "hidden";
}

function closePlace() {
    modal.classList.remove("open");
    document.body.style.overflow = "";
}

document.querySelectorAll(".details-button").forEach(button => {
    button.addEventListener("click", () => {
        openPlace(button.dataset.place);
    });
});

closeModal.addEventListener("click", closePlace);
modalOverlay.addEventListener("click", closePlace);

document.addEventListener("keydown", event => {
    if (event.key === "Escape") {
        closePlace();
    }
});

document.getElementById("keepExploring").addEventListener("click", closePlace);

planPlace.addEventListener("click", () => {
    if (!selectedPlace) return;

    const destination = document.getElementById("destination");

    const option = [...destination.options].find(
        item => item.textContent.trim() === selectedPlace.title
    );

    if (option) {
        destination.value = option.value;
    }

    closePlace();

    setTimeout(() => {
        document.getElementById("booking").scrollIntoView({
            behavior: "smooth"
        });
    }, 150);
});

/* Mobile navigation */
const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");

menuToggle.addEventListener("click", () => {
    navLinks.classList.toggle("show");
});

navLinks.querySelectorAll("a").forEach(link => {
    link.addEventListener("click", () => {
        navLinks.classList.remove("show");
    });
});

/* Booking form demo */
const bookingForm = document.getElementById("bookingForm");
const successMessage = document.getElementById("successMessage");
const visitDate = document.getElementById("visitDate");

visitDate.min = new Date().toISOString().split("T")[0];

bookingForm.addEventListener("submit", event => {
    event.preventDefault();

    const name = document.getElementById("name").value.trim();
    const destination = document.getElementById("destination").value;
    const date = document.getElementById("visitDate").value;

    successMessage.style.display = "block";
    successMessage.textContent =
        `✓ Thank you, ${name}! Your trip request for ${destination} on ${date} has been received in this demo website.`;

    bookingForm.reset();
});

